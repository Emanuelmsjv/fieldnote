import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const EVAL_DIR = resolve(ROOT, "data/eval");
const OUT_MD = resolve(ROOT, "docs/eval.md");

function pct(x) {
  return `${(x * 100).toFixed(1)}%`;
}

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8").replace(/^﻿/, ""));
}

const SIZE_ORDER = { tiny: 1, base: 2, small: 3, medium: 4, large: 5 };

function sizeRank(label) {
  const lower = String(label).toLowerCase();
  const key = Object.keys(SIZE_ORDER).find((k) => lower.includes(k));
  return key ? SIZE_ORDER[key] : 99;
}

function sizeName(label) {
  const lower = String(label).toLowerCase();
  return Object.keys(SIZE_ORDER).find((k) => lower.includes(k)) ?? label;
}

function loadResults() {
  const files = readdirSync(EVAL_DIR).filter((f) => f.endsWith(".json") && f !== "log.jsonl");
  const results = [];
  for (const f of files) {
    try {
      const raw = readJson(resolve(EVAL_DIR, f));
      if (raw && Array.isArray(raw.rows)) results.push(raw);
    } catch {
      /* skip malformed */
    }
  }
  return results.sort((a, b) => sizeRank(a.label) - sizeRank(b.label));
}

function worstSentences(result, n) {
  return [...result.rows]
    .filter((r) => r.birdRefs > 0)
    .sort((a, b) => b.wer - a.wer)
    .slice(0, n);
}

function main() {
  const results = loadResults();
  if (results.length === 0) {
    console.error("No evaluation results in data/eval. Run src/evaluate.mjs first.");
    process.exitCode = 1;
    return;
  }

  const smallest = results[0];
  const largest = results[results.length - 1];
  const scalingHelped =
    results.length < 2 || largest.birdNameTokens.recall >= smallest.birdNameTokens.recall;
  const params = sizeName;

  const lines = [];
  lines.push("# Offline transcription of field notes: measured results");
  lines.push("");
  lines.push("Generated by `npm run eval:compare`.");
  lines.push("");

  lines.push("## Headline");
  lines.push("");
  if (results.length > 1 && !scalingHelped) {
    lines.push(
      `**Scaling the model made the domain vocabulary worse.** \`${params(largest.label)}\` is the larger ` +
        `model and recovers ${pct(largest.birdNameTokens.recall)} of bird-name tokens; the smaller ` +
        `\`${params(smallest.label)}\` recovers ${pct(smallest.birdNameTokens.recall)}. Corpus word error ` +
        `rate also got worse, from ${pct(smallest.corpusWer)} to ${pct(largest.corpusWer)}.`,
    );
    lines.push("");
    lines.push("Both are Whisper checkpoints at the same quantisation, differing only in size. Buying a");
    lines.push("bigger general-purpose model does not buy you a regional bird vocabulary.");
  } else if (results.length > 1) {
    lines.push(
      `Scaling helps: \`${params(largest.label)}\` recovers ${pct(largest.birdNameTokens.recall)} of ` +
        `bird-name tokens against ${pct(smallest.birdNameTokens.recall)} for \`${params(smallest.label)}\`.`,
    );
  } else {
    lines.push(`Only one model was evaluated: \`${params(smallest.label)}\`.`);
  }
  lines.push("");
  lines.push("Ordinary speech is transcribed perfectly by every model tested. The difficulty is specific:");
  lines.push("multi-syllable compound names that do not occur in general English training data.");
  lines.push("");

  lines.push("## Results");
  lines.push("");
  lines.push("model | size class | exact matches | corpus WER | ordinary WER | species WER | mixed WER | bird-name tokens recovered");
  lines.push(":--- | :--- | ---: | ---: | ---: | ---: | ---: | ---:");
  for (const r of results) {
    lines.push(
      `\`${params(r.label)}\` | ${r.dtype} | ${r.exactMatches}/${r.sentences} (${pct(r.exactMatches / r.sentences)}) | ` +
      `${pct(r.corpusWer)} | ${pct(r.byCategory.ordinary?.meanWer ?? 0)} | ` +
      `${pct(r.byCategory.species?.meanWer ?? 0)} | ${pct(r.byCategory.mixed?.meanWer ?? 0)} | ` +
      `**${pct(r.birdNameTokens.recall)}** (${r.birdNameTokens.recovered}/${r.birdNameTokens.total})`,
    );
  }
  lines.push("");

  lines.push("## Why this matters for the design");
  lines.push("");
  lines.push("If transcription of bird names were reliable, a spoken field note could be trusted as data.");
  lines.push("It is not, so this project treats every transcript as a draft:");
  lines.push("");
  lines.push("1. The transcript is always shown to the user, never hidden.");
  lines.push("2. Extracted species are matched against the local species list and anything unmatched is");
  lines.push("   flagged rather than silently dropped or silently accepted.");
  lines.push("3. Corrections the user makes are kept, and exported as a fine-tuning corpus.");
  lines.push("");
  lines.push("Step 3 is only possible with open weights. A cloud speech API cannot be fine-tuned on");
  lines.push("Chidambaram bird vocabulary, and it would require shipping audio off the machine to do it.");
  lines.push("That is the argument this project is making, and the numbers above are the evidence.");
  lines.push("");

  lines.push("## Sentences the best model still gets wrong");
  lines.push("");
  for (const r of worstSentences(largest, 8)) {
    lines.push(`### \`${r.id}\` — WER ${pct(r.wer)}, bird tokens ${r.birdHits}/${r.birdRefs}`);
    lines.push("");
    lines.push(`- reference:  *${r.reference}*`);
    lines.push(`- transcript: *${r.hypothesis.trim()}*`);
    lines.push("");
  }

  lines.push("## Method");
  lines.push("");
  lines.push("Audio fixtures are generated deterministically from `data/eval/sentences.json` using the");
  lines.push("Windows SAPI voice, so the set is regenerable and the audio is committed. Categories:");
  lines.push("`ordinary` is plain everyday speech, `species` is dominated by bird names, `mixed` is");
  lines.push("field-note phrasing with numbers and place names.");
  lines.push("");
  lines.push("Word error rate is standard Levenshtein over whitespace tokens after lowercasing, punctuation");
  lines.push("stripping and expanding digits to words. Bird-name recovery is a bag-of-words check of whether");
  lines.push("each bird-name token in the reference appears anywhere in the transcript, which catches the");
  lines.push("specific failure where a name is not mispronounced but dropped or split.");
  lines.push("");

  mkdirSync(dirname(OUT_MD), { recursive: true });
  writeFileSync(OUT_MD, lines.join("\n"), "utf8");

  console.log("");
  for (const r of results) {
    console.log(
      `  ${params(r.label).padEnd(5)} bird-name recall ${pct(r.birdNameTokens.recall).padStart(6)}  ` +
      `species WER ${pct(r.byCategory.species?.meanWer ?? 0).padStart(6)}  ` +
      `ordinary WER ${pct(r.byCategory.ordinary?.meanWer ?? 0).padStart(5)}  ` +
      `exact ${r.exactMatches}/${r.sentences}`,
    );
  }
  console.log("");
  console.log(scalingHelped
    ? "  scaling helped on bird-name recall"
    : "  scaling did NOT help: the larger model recovers fewer bird-name tokens");
  console.log(`wrote ${OUT_MD}`);
}

main();
